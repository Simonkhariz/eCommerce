<?php

declare(strict_types=1);

/**
 * Test runner: builds a throw-away database, starts the API against it, runs every suite,
 * then cleans up. Your development database (.env DB_DATABASE) is never touched.
 *
 *   php backend/tests/run.php                 run all suites
 *   php backend/tests/run.php Security Admin  run suites whose file name contains these words
 *   php backend/tests/run.php --keep          keep the test database afterwards (for debugging)
 *
 * Requirements: MySQL running (XAMPP) with the credentials in backend/.env, PHP with curl.
 * Payment signature tests use the Kora/Monnify keys from backend/.env (sandbox keys are fine;
 * nothing is sent to the gateways).
 */

if (PHP_SAPI !== 'cli') {
    exit;
}

define('BASE_PATH', dirname(__DIR__));
require_once BASE_PATH . '/src/autoload.php';

use App\Config\Env;

$args = array_slice($argv, 1);
$keep = in_array('--keep', $args, true);
$filters = array_values(array_filter($args, static fn ($a) => !str_starts_with($a, '--')));

Env::load(BASE_PATH . '/.env');
$devDb = (string) Env::get('DB_DATABASE', 'shopco_dev');
$testDb = (string) (getenv('TEST_DB_DATABASE') ?: 'shopco_test');
if ($testDb === $devDb) {
    fwrite(STDERR, "The test database name must differ from DB_DATABASE ({$devDb}).\n");
    exit(2);
}
$port = (int) (getenv('TEST_API_PORT') ?: 8099);

// 1. .env.testing: a copy of .env pointed at the test database and a separate mail log.
$envFile = BASE_PATH . '/.env.testing';
$overrides = [
    'DB_DATABASE' => $testDb,
    'APP_ENV' => 'testing',
    'APP_DEBUG' => 'false',
    'MAIL_MAILER' => 'log',
    'MAIL_LOG_PATH' => 'storage/logs/mail.testing.log',
    'MAIL_SEND_IMMEDIATELY' => 'true',
];
$lines = file_exists(BASE_PATH . '/.env') ? file(BASE_PATH . '/.env', FILE_IGNORE_NEW_LINES) : [];
$lines = array_values(array_filter($lines, static function (string $line) use ($overrides): bool {
    $name = trim(strstr($line, '=', true) ?: '');
    return !array_key_exists($name, $overrides);
}));
foreach ($overrides as $k => $v) {
    $lines[] = "{$k}={$v}";
}
file_put_contents($envFile, "# Generated by tests/run.php – do not edit or commit.\n" . implode("\n", $lines) . "\n");
@unlink(BASE_PATH . '/storage/logs/mail.testing.log');

$env = array_merge(getenv(), ['SHOPCO_ENV_FILE' => $envFile, 'API_URL' => "http://127.0.0.1:{$port}/api/v1"]);
$php = PHP_BINARY;

$run = static function (array $cmd, bool $echo = true) use ($env): int {
    $proc = proc_open($cmd, [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes, BASE_PATH, $env);
    $out = stream_get_contents($pipes[1]) . stream_get_contents($pipes[2]);
    $code = proc_close($proc);
    if ($echo || $code !== 0) {
        echo $out;
    }
    return $code;
};

// 2. Fresh database: drop, migrate, seed.
$mysqli = @new mysqli((string) Env::get('DB_HOST', '127.0.0.1'), (string) Env::get('DB_USERNAME', 'root'), (string) Env::get('DB_PASSWORD', ''), '', Env::int('DB_PORT', 3306));
if ($mysqli->connect_errno) {
    fwrite(STDERR, "Cannot connect to MySQL: {$mysqli->connect_error}\n");
    exit(2);
}
$mysqli->query("DROP DATABASE IF EXISTS `{$testDb}`");
$mysqli->close();

echo "Preparing {$testDb}...\n";
if ($run([$php, BASE_PATH . '/migrations/migrate.php'], false) !== 0 || $run([$php, BASE_PATH . '/seeds/seed.php'], false) !== 0) {
    fwrite(STDERR, "Could not prepare the test database.\n");
    exit(2);
}

// 3. API server on the test database.
$server = proc_open(
    [$php, '-S', "127.0.0.1:{$port}", '-t', BASE_PATH . '/public'],
    [1 => ['file', BASE_PATH . '/storage/logs/test-server.log', 'w'], 2 => ['file', BASE_PATH . '/storage/logs/test-server.log', 'a']],
    $pipes,
    BASE_PATH,
    $env
);
$ready = false;
for ($i = 0; $i < 50 && !$ready; $i++) {
    usleep(200000);
    $ready = @file_get_contents("http://127.0.0.1:{$port}/api/v1/health") !== false;
}
if (!$ready) {
    fwrite(STDERR, "The test API did not start on port {$port} (see storage/logs/test-server.log).\n");
    proc_terminate($server);
    exit(2);
}
echo "Test API running on 127.0.0.1:{$port}\n\n";

// 4. Suites.
$suites = glob(__DIR__ . '/*Test.php') ?: [];
sort($suites);
if ($filters !== []) {
    $suites = array_values(array_filter($suites, static function (string $file) use ($filters): bool {
        foreach ($filters as $f) {
            if (stripos(basename($file), $f) !== false) {
                return true;
            }
        }
        return false;
    }));
}

$summary = [];
$failedSuites = 0;
foreach ($suites as $suite) {
    $start = microtime(true);
    $proc = proc_open([$php, $suite], [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes, BASE_PATH, $env);
    $out = stream_get_contents($pipes[1]) . stream_get_contents($pipes[2]);
    $code = proc_close($proc);
    echo $out . "\n";
    preg_match('/RESULT: (\d+) passed, (\d+) failed/', $out, $m);
    $summary[] = [basename($suite, '.php'), (int) ($m[1] ?? 0), (int) ($m[2] ?? 0), $code, round(microtime(true) - $start, 1)];
    if ($code !== 0) {
        $failedSuites++;
    }
}

// 5. Tear down.
proc_terminate($server);
proc_close($server);
if (!$keep) {
    $mysqli = new mysqli((string) Env::get('DB_HOST', '127.0.0.1'), (string) Env::get('DB_USERNAME', 'root'), (string) Env::get('DB_PASSWORD', ''), '', Env::int('DB_PORT', 3306));
    $mysqli->query("DROP DATABASE IF EXISTS `{$testDb}`");
    $mysqli->close();
}

echo str_repeat('=', 64) . "\n";
$totalPass = $totalFail = 0;
foreach ($summary as [$name, $pass, $fail, $code, $secs]) {
    printf("%-34s %4d passed %3d failed %6.1fs %s\n", $name, $pass, $fail, $secs, $code === 0 ? '' : '  <-- FAILED');
    $totalPass += $pass;
    $totalFail += $fail;
}
echo str_repeat('=', 64) . "\n";
printf("TOTAL %d passed, %d failed in %d suites%s\n", $totalPass, $totalFail, count($summary), $keep ? " (kept database {$testDb})" : '');
exit($failedSuites > 0 ? 1 : 0);
